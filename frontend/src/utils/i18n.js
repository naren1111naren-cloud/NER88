/**
 * Localizes an Alert object according to the selected language with variable injection and fallback.
 */
export const localizeAlert = (alert, lang = 'en') => {
  if (!alert) return { title: '', message: '', action: '' };

  const targetLang = translations[lang] ? lang : 'en';
  const alertType = alert.alert_type || '';
  const template = alertTemplates[alertType];

  if (!template) {
    // If no specific template exists, fallback safely to original server title/message
    return {
      title: alert.title || 'Operational Notification',
      message: alert.message || '',
      action: alert.recommended_action || ''
    };
  }

  const loc = alert.location || alert.title || 'North Eastern Corridor';
  const replaceVars = (str) => {
    if (!str) return '';
    return str
      .replace(/{location}/g, loc)
      .replace(/{severity}/g, alert.severity || 'HIGH');
  };

  const localizedTitle = template.title[targetLang] 
    ? replaceVars(template.title[targetLang])
    : (template.title.en ? replaceVars(template.title.en) : alert.title);

  const localizedMessage = template.message[targetLang]
    ? replaceVars(template.message[targetLang])
    : (template.message.en ? replaceVars(template.message.en) : alert.message);

  const localizedAction = template.action && template.action[targetLang]
    ? replaceVars(template.action[targetLang])
    : (template.action && template.action.en ? replaceVars(template.action.en) : alert.recommended_action);

  return {
    title: localizedTitle,
    message: localizedMessage,
    action: localizedAction
  };
};
