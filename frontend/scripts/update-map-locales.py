def update_locales():
    for lang, data in TRANSLATIONS.items():
        file_path = os.path.join(LOCALES_DIR, f"{lang}.json")
        if not os.path.exists(file_path):
            print(f"[SKIP] Locale file not found: {file_path}")
            continue

        with open(file_path, "r", encoding="utf-8") as f:
            existing_data = json.load(f)

        # Merge map
        if "map" in data:
            if "map" not in existing_data:
                existing_data["map"] = {}
            for k, v in data["map"].items():
                existing_data["map"][k] = v

        # Merge footer
        if "footer" in data:
            if "footer" not in existing_data:
                existing_data["footer"] = {}
            for k, v in data["footer"].items():
                existing_data["footer"][k] = v

        # Merge assistant extras
        if "assistant" in data:
            if "assistant" not in existing_data:
                existing_data["assistant"] = {}
            for k, v in data["assistant"].items():
                existing_data["assistant"][k] = v

        with open(file_path, "w", encoding="utf-8") as f:
            json.dump(existing_data, f, ensure_ascii=False, indent=2)
        print(f"[UPDATED] {lang}.json successfully updated.")

if __name__ == "__main__":
    update_locales()
